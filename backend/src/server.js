import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import authRoutes from "./routes/auth.js";
import doctorRoutes from "./routes/doctors.js";
import appointmentRoutes from "./routes/appointments.js";
import queueRoutes from "./routes/queue.js";
import adminRoutes from "./routes/admin.js";
const app = express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL || "http://localhost:3000"}));
app.use(express.json({limit:"1mb"}));
app.use("/api",rateLimit({windowMs:15*60*1000,max:300}));
app.get("/api/health",(_req,res)=>res.json({status:"ok",service:"MediCare API"}));
app.use("/api/auth",authRoutes);
app.use("/api/doctors",doctorRoutes);
app.use("/api/appointments",appointmentRoutes);
app.use("/api/queue",queueRoutes);
app.use("/api/admin",adminRoutes);
app.use((err,_req,res,_next)=>{
  console.error(err);
  if (err.name==="ZodError") return res.status(400).json({message:"Invalid input",errors:err.issues});
  if (err.code==="P2002") return res.status(409).json({message:"A record with this value already exists"});
  res.status(500).json({message:"Internal server error"});
});
const port=process.env.PORT || 5000;
app.listen(port,()=>console.log(`MediCare API running on ${port}`));
